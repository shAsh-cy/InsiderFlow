#!/usr/bin/env node
/**
 * Which modules are actually inside a built chunk, and how many bytes each.
 *
 * ── WHY THIS EXISTS ───────────────────────────────────────────────────
 *
 * r17 measured `/screener` at 62 on mobile Lighthouse against 76 in r4, and
 * attributed the deficit to 835ms of script evaluation inside one 170 kB
 * chunk. It could not say what was IN that chunk. The guess written down at
 * the time was TanStack Table plus TanStack Virtual, and it was labelled a
 * guess, because a minified chunk carries no library names and a plausible
 * attribution is how r16's wrong performance claim happened.
 *
 * This reads the source map instead of guessing. Build with `ANALYZE=1` and
 * every generated byte is attributed to the original module it came from.
 *
 * ── WHY NOT @next/bundle-analyzer ─────────────────────────────────────
 *
 * It answers the same question and costs a dependency tree — webpack-bundle-
 * analyzer and its transitive set — added to a repository whose r12 spent a
 * round removing four advisories and 50 packages from the lockfile. The
 * attribution itself is a VLQ decode and a subtraction; that is cheaper to
 * own than to import.
 *
 * ── HOW THE ATTRIBUTION WORKS ─────────────────────────────────────────
 *
 * A source map's `mappings` field is a list of segments per generated line:
 * [generatedColumn, sourceIndex, sourceLine, sourceColumn], each field
 * delta-encoded as base64 VLQ. Bytes between one segment's column and the
 * next segment's column on the same generated line belong to the source the
 * FIRST of those two segments names. Summing those runs per source gives
 * the bytes each original module contributes to the minified output, which
 * is the number that matters — not the size of the original file, which
 * counts comments and types that never ship.
 *
 * Usage:
 *   ANALYZE=1 pnpm --filter @insiderflow/web exec next build
 *   node scripts/analyze-chunks.mjs                    # every chunk >= 100kB
 *   node scripts/analyze-chunks.mjs 6121               # one chunk
 *   node scripts/analyze-chunks.mjs --top=25
 */
import { readFileSync, readdirSync } from "node:fs";
import { join, resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const CHUNK_DIR = join(root, "apps", "web", ".next", "static", "chunks");

const args = process.argv.slice(2);
const flag = (name, fallback) => {
  const hit = args.find((a) => a.startsWith(`--${name}=`));
  return hit ? hit.slice(name.length + 3) : fallback;
};
const TOP = Number(flag("top", "15"));
const MIN_BYTES = Number(flag("min", "102400"));
const filter = args.find((a) => !a.startsWith("--"));

const B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
const CHAR = new Map([...B64].map((c, i) => [c, i]));

/** Decode one base64-VLQ field, returning [value, nextIndex]. */
function decodeVlq(text, start) {
  let result = 0;
  let shift = 0;
  let i = start;
  for (;;) {
    const digit = CHAR.get(text[i]);
    if (digit === undefined) throw new Error(`bad VLQ character ${JSON.stringify(text[i])}`);
    i += 1;
    result += (digit & 31) << shift;
    if ((digit & 32) === 0) break;
    shift += 5;
  }
  const negative = result & 1;
  result >>= 1;
  return [negative ? -result : result, i];
}

/**
 * Bytes of generated output attributable to each source.
 *
 * The last segment on a generated line runs to the end of that line, so the
 * line lengths of the generated file are needed as well as the mappings.
 */
function attribute(mapJson, generatedText) {
  const map = JSON.parse(mapJson);
  const lineLengths = generatedText.split("\n").map((l) => l.length);
  const bytes = new Map();

  let genLine = 0;
  let sourceIndex = 0;
  const groups = map.mappings.split(";");

  for (const group of groups) {
    if (group) {
      const segments = group.split(",").filter(Boolean);
      let genColumn = 0;
      const decoded = [];
      for (const segment of segments) {
        let i = 0;
        const fields = [];
        while (i < segment.length) {
          const [value, next] = decodeVlq(segment, i);
          fields.push(value);
          i = next;
        }
        genColumn += fields[0];
        if (fields.length >= 4) sourceIndex += fields[1];
        decoded.push({ column: genColumn, source: fields.length >= 4 ? sourceIndex : null });
      }
      // Each segment owns the run up to the next segment's column, and the
      // final one owns the rest of the generated line.
      for (let s = 0; s < decoded.length; s += 1) {
        const from = decoded[s];
        if (from.source === null) continue;
        const to = decoded[s + 1];
        const end = to ? to.column : (lineLengths[genLine] ?? from.column);
        const run = Math.max(0, end - from.column);
        const name = map.sources[from.source] ?? "<unknown>";
        bytes.set(name, (bytes.get(name) ?? 0) + run);
      }
    }
    genLine += 1;
  }
  return bytes;
}

/** Collapse a webpack source path to the thing a human decides about. */
function bucket(source) {
  const clean = source.replace(/^webpack:\/\/(_N_E)?\//, "").replace(/\?.*$/, "");
  const nm = clean.lastIndexOf("node_modules/");
  if (nm !== -1) {
    const rest = clean.slice(nm + "node_modules/".length);
    const parts = rest.split("/");
    return parts[0].startsWith("@") ? `${parts[0]}/${parts[1]}` : parts[0];
  }
  if (clean.includes("/src/") || clean.startsWith("src/")) return clean;
  return clean;
}

const files = readdirSync(CHUNK_DIR)
  .filter((f) => f.endsWith(".js"))
  .filter((f) => (filter ? f.includes(filter) : true))
  .map((f) => ({
    name: f,
    path: join(CHUNK_DIR, f),
    size: readFileSync(join(CHUNK_DIR, f)).length,
  }))
  .filter((f) => (filter ? true : f.size >= MIN_BYTES))
  .sort((a, b) => b.size - a.size);

if (files.length === 0) {
  console.error(
    `No chunks matched under ${CHUNK_DIR}.\n` +
      "Build first: ANALYZE=1 pnpm --filter @insiderflow/web exec next build",
  );
  process.exit(1);
}

const kb = (n) => `${(n / 1024).toFixed(1)} kB`;

for (const file of files) {
  let mapJson;
  try {
    mapJson = readFileSync(`${file.path}.map`, "utf8");
  } catch {
    console.error(
      `${file.name} (${kb(file.size)}) — NO SOURCE MAP.\n` +
        "  Rebuild with ANALYZE=1, or this chunk cannot be attributed.\n",
    );
    continue;
  }

  const perSource = attribute(mapJson, readFileSync(file.path, "utf8"));
  const perBucket = new Map();
  let mapped = 0;
  for (const [source, n] of perSource) {
    mapped += n;
    const key = bucket(source);
    perBucket.set(key, (perBucket.get(key) ?? 0) + n);
  }

  const ranked = [...perBucket].sort((a, b) => b[1] - a[1]);
  console.log(`\n${file.name} — ${kb(file.size)} on disk, ${kb(mapped)} attributed`);
  console.log("".padEnd(74, "─"));
  for (const [name, n] of ranked.slice(0, TOP)) {
    const share = ((n / mapped) * 100).toFixed(1).padStart(5);
    console.log(`  ${kb(n).padStart(9)}  ${share}%  ${name}`);
  }
  const rest = ranked.slice(TOP).reduce((sum, [, n]) => sum + n, 0);
  if (rest > 0) {
    console.log(
      `  ${kb(rest).padStart(9)}  ${((rest / mapped) * 100).toFixed(1).padStart(5)}%  ` +
        `(${ranked.length - TOP} more)`,
    );
  }
}
